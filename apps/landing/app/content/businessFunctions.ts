// Business function content registry.
// Each BusinessFunction drives one /workflows/[slug] page.
// Workflow-level detail (WorkflowDef) is displayed via expandable panels —
// there are intentionally no standalone workflow routes.

export type WorkflowArchetype =
  | "INTAKE → TRIAGE → RESOLVE"
  | "RECONCILE → INVESTIGATE → RESOLVE"
  | "EXTRACT → VALIDATE → ROUTE"
  | "MONITOR → DETECT → ACT"
  | "COORDINATE → EXECUTE → CONFIRM"
  | "REQUEST → REVIEW → APPROVE";

export interface WorkflowDef {
  slug: string;
  name: string;
  description: string;
  operationalDrag: string;
  archetype: WorkflowArchetype;
  typicalSteps: string[];
  systems: string[];
  aiLeverage: string[];
  humanBoundaries: string[];
  outcomes: string[];
  capabilities: string[];
  tags: string[];
  playbookSlug?: string;
  caseStudySlug?: string;
}

export interface DragPattern {
  label: string;
  description: string;
}

export interface FlowStep {
  label: string;
  type: "input" | "system" | "human" | "decision" | "output";
}

export interface ManualFlow {
  steps: FlowStep[];
  painPoints: string[]; // zero-based index strings
}

export interface AIAssistedFlow {
  steps: FlowStep[];
  automatedSteps: string[];
  humanSteps: string[];
}

export interface FunctionMetric {
  label: string;
  description: string;
  unit?: string;
}

export interface CapabilityNote {
  slug: string; // matches CAPABILITIES[].id
  relevance: string;
}

export interface BusinessFunction {
  slug: string;
  catalogSlug: string;
  name: string;
  shortName: string;
  eyebrow: string;
  title: string;
  description: string;
  dragHeadline: string;
  dragIntro: string;
  dragPatterns: DragPattern[];
  manualFlow: ManualFlow;
  aiAssistedFlow: AIAssistedFlow;
  workflows: WorkflowDef[];
  aiApplicationIntro: string;
  capabilities: CapabilityNote[];
  metrics: FunctionMetric[];
  systems: string[];
  relatedFunctions: string[];
  metaTitle: string;
  metaDescription: string;
}

